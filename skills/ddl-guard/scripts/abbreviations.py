# ── 标准缩写白名单（仅作符号集中，ddl_check 未引用，预留扩展） ──────
# 用法示例：当需做"非标准缩写"反向检查时，遍历该集合发现 key ∉ LONG_TO_SHORT
# 即报错。ddl-guard 当前仅做"长写法 → 缩写"单向检查，未启用该集合。

STANDARD_SHORT: set[str] = set(LONG_TO_SHORT.values())


def strip_index_prefix(name: str) -> str:
    """去掉索引名前缀 `ix_` / `uk_`，返回剩余分词字符串。"""
    low = name.lower()
    if low.startswith("uk_"):
        return low[3:]
    if low.startswith("ix_"):
        return low[3:]
    return low


def iter_abbrev_violations(name: str) -> list[tuple[str, str]]:
    """对名称（含 `snake_case` 分词）逐分词检查，返回 [(命中分词, 标准缩写), ...]。

    字段名/表名直接传入；索引名应先经 ``strip_index_prefix`` 处理。
    """
    violations: list[tuple[str, str]] = []
    for part in name.lower().split("_"):
        if part in LONG_TO_SHORT:
            violations.append((part, LONG_TO_SHORT[part]))
    return violations
